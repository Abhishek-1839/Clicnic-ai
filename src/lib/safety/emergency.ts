// Rule-based emergency detection. Runs BEFORE any LLM call so that an AI outage,
// a rate limit or a prompt-injection attempt can never skip the safety path.
//
// Trade-off: this is deliberately over-sensitive. It does not try to understand
// negation ("no chest pain"), because routing a harmless message to the emergency
// response is far cheaper than missing a real emergency.

export type EmergencyKind = "medical" | "self_harm";

export type EmergencyResult = {
  urgent: boolean;
  kind: EmergencyKind | null;
  matched: string | null;
};

const SELF_HARM: RegExp[] = [
  /\bsuicid\w*/,
  /\bkill (myself|my self)\b/,
  /\bend (my|this) life\b/,
  /\b(want|wanna|going) to die\b/,
  /\bdon t want to (live|be alive)\b/,
  /\bhurt(ing)? myself\b/,
  /\bself harm\b/,
  /\bharm(ing)? myself\b/,
];

const MEDICAL: RegExp[] = [
  /\bchest (pain|pressure|tightness|discomfort)\b/,
  /\bheart attack\b/,
  /\b(can t|cannot|cant|unable to|trouble|difficulty|hard to|struggling to) breathe?\b/,
  /\b(trouble|difficulty|struggling) breathing\b/,
  /\b(short(ness)? of breath)\b/,
  /\b(not|stopped) breathing\b/,
  /\bstroke\b/,
  /\bface (is )?droop\w*/,
  /\bslurred speech\b/,
  /\b(unconscious|unresponsive|passed out|collapsed)\b/,
  /\bseizure\w*/,
  /\b(severe|heavy|uncontrol\w*|profuse) bleeding\b/,
  /\bbleeding (heavily|badly|a lot)\b/,
  /\bwon t stop bleeding\b/,
  /\boverdos\w*/,
  /\bpoison\w*/,
  /\bchoking\b/,
  /\banaphyla\w*/,
  /\bthroat (is )?(closing|swelling|swollen)\b/,
  /\b(unbearable|excruciating) pain\b/,
  /\bbaby (is )?(not|isn t) (responding|breathing|moving)\b/,
];

function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/['’`]/g, " ") // can't -> can t
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function detectEmergency(text: string): EmergencyResult {
  const t = normalize(text);
  for (const re of SELF_HARM) {
    const m = t.match(re);
    if (m) return { urgent: true, kind: "self_harm", matched: m[0] };
  }
  for (const re of MEDICAL) {
    const m = t.match(re);
    if (m) return { urgent: true, kind: "medical", matched: m[0] };
  }
  return { urgent: false, kind: null, matched: null };
}

/** Fixed responses. Never generated by an LLM. Shown with the "AI-generated" label by the chat UI. */
export function emergencyReply(kind: EmergencyKind): string {
  if (kind === "self_harm") {
    return (
      "I'm really sorry you're going through this. I'm an automated administrative assistant and can't help with this " +
      "safely, but you deserve support right now. Please contact your local emergency number (112 in India) or a crisis " +
      "helpline, or reach out to someone you trust and stay with them. A member of our clinic staff has been alerted."
    );
  }
  return (
    "This may be an emergency. Please call your local emergency number right now (112 in India) or go to the nearest " +
    "emergency department. I'm an automated administrative assistant and cannot assess symptoms. " +
    "A member of our clinic staff has been alerted."
  );
}
